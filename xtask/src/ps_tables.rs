//! Generates `crates/soul-audio-core/src/formats/aac/ps/tables.rs` — every
//! transcendental/const table the Parametric Stereo (PS) decoder needs, so
//! no downstream PS task (2-8) ever calls `libm` at runtime: the 10 faad2
//! Huffman decode trees (§3/V1), IID/ICC dequant + mixing-angle tables
//! (§3/V2), the IPD/OPD angle + atan2-free complex smoothing tables
//! (§3/§7/V2.c), the faad2 Type-B/β/γ mixing-optimization tables (§7/V2.d),
//! the flattened band maps (§4/V3), the hybrid-filterbank modulated complex
//! filters (§5/V4), and the decorrelation allpass/phase tables (§6/V5). Run
//! via `cargo xtask gen-ps-tables`; the output is checked in and CI-guarded
//! by [`check`] (wired into `xtask verify`), mirroring `sbr_tables.rs`.
//!
//! # Provenance
//! Every verbatim (hand/script-transcribed) table below was extracted
//! **programmatically** (a small Python script, not hand-retyped) from the
//! actual upstream C sources fetched directly via `curl` (raw bytes, no LLM
//! summarization in the loop — WebFetch's small-model summarization was
//! tried first and caught corrupting a large table, so this task fetches
//! raw and parses with a script instead):
//! - faad2 `libfaad/ps_syntax.c` (`master`, `knik0/faad2`): the 10 Huffman
//!   binary-tree tables (V1.a).
//! - faad2 `libfaad/ps_tables.h`: `sf_iid_normal/fine` (V2.a), `cos/sin_alphas`
//!   (V2.b), the Type-B/β/γ mixing-optimization tables (V2.d, FULL bodies —
//!   not just anchors), and `Phi_Fract_*`/`Q_Fract_allpass_*` (V5, FULL
//!   bodies).
//! - faad2 `libfaad/ps_dec.c`: `filter_a`, `delay_length_d` ({3,4,5}),
//!   `short_delay_band` (35, confirming `DELAY_D`'s 14/1 split point), and
//!   (cross-check only, not emitted) `group_border20/34`/`map_group2bk20/34`.
//! - FFmpeg `libavcodec/aacpsdata.c` (`master`): `ff_k_to_i_20/34` (V3),
//!   cross-checked byte-for-byte against `ps-reference-verbatim.md` (match).
//! - FFmpeg `libavcodec/aacps_tablegen.h`: cross-check for `g0_Q12/g1_Q8/
//!   g2_Q4/g0_Q8` (V4, exact match) and the modulated-filter formula
//!   (`make_filters_from_proto`, exact match to `ps-reference.md` §5's
//!   `exp(-i*2*pi*(q+0.5)*(n-6)/bands)`), plus the PD smoothing algorithm.
//!
//! `ps-reference-verbatim.md`'s hand-transcribed `t_huff_iid_fine[60]` was
//! found to be missing 4 rows (56 present) when cross-checked against the
//! real source; the programmatic extraction below is the corrected,
//! byte-exact table (see `ps-task-1-report.md`).
//!
//! # Verbatim vs computed
//! **Verbatim** (transcribed from the sources above, `_F64`/`_I8`/`_U8`
//! suffix on the host-side source constant; a `#[cfg(test)]` anchor below
//! re-checks each): all 10 Huffman trees, `SF_IID_NORMAL/FINE`, `ICC_INVQ`,
//! `COS_ALPHAS`/`SIN_ALPHAS`, the V2.d β/γ/Type-B tables, `FF_K_TO_I_20/34`,
//! the four hybrid FIR half-coefficient prototypes, `FILTER_A`,
//! `NUM_SAMPLE_DELAY_SER`, `PHI_FRACT_*`/`Q_FRACT_ALLPASS_*`.
//!
//! **Computed** host-side (`f64` trig, this file only — never emitted as
//! runtime code): `IPDOPD_COS/SIN` (closed form `theta = index*pi/4`),
//! `PD_RE_SMOOTH`/`PD_IM_SMOOTH` (FFmpeg `aacps_tablegen.h`'s atan2-free
//! 3-history-sample complex smoothing — see [`pd_smooth`] doc for the
//! `[512]` sizing correction vs the design brief's assumed `[64]`), the
//! modulated complex hybrid filters `HYB_FILT_{12,8,4,6}` (from the V4
//! protos via the §5 formula — see [`hyb_filt_6`] doc for `HYB_FILT_6`'s
//! "direct-6" derivation), and `DELAY_D` (the 14/1 step function).
//!
//! # V2.d decision
//! Emits the **faad2 Type-B/β/γ tables** (the brief's recommended path):
//! `COS_BETAS_NORMAL/FINE`, `SIN_BETAS_NORMAL/FINE`, `COS_GAMMAS_NORMAL/FINE`,
//! `SIN_GAMMAS_NORMAL/FINE`, `SINCOS_ALPHAS_B_NORMAL/FINE` — all FULL bodies
//! (not just the size+anchor the brief allowed), since the real source was
//! directly fetchable and programmatically parseable (no transcription-risk
//! reason to defer to Task 8). Two dimensions differ from the brief's V2.d
//! table (which only gave illustrative anchors, not full bodies): the real
//! `cos/sin_gammas_fine` are `[16][8]`, not `[8][8]` — matching the fine/
//! coarse split of `cos/sin_betas_fine` `[16][8]` one row up.

