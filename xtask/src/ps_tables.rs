/// IPD/OPD angle table (V2.c): `theta = index * pi/4`, closed form.
fn ipdopd_cos_sin() -> ([f32; 8], [f32; 8]) {
    let mut c = [0f32; 8];
    let mut s = [0f32; 8];
    for (q, (cq, sq)) in c.iter_mut().zip(s.iter_mut()).enumerate() {
        let a = q as f64 * PI / 4.0;
        *cq = a.cos() as f32;
        *sq = a.sin() as f32;
    }
    (c, s)
}

/// IPD/OPD atan2-free complex smoothing table (V2.c / ps-reference.md §7),
/// FFmpeg `aacps_tablegen.h` `ps_tableinit()`'s exact algorithm (verified
/// against the real fetched source, not the design brief's paraphrase):
/// `re_smooth = 0.25*cos(pd0) + 0.5*cos(pd1) + cos(pd2)` (and the `sin`
/// analogue for `im_smooth`), normalized to unit magnitude, where `pd0` is
/// the OLDEST of 3 history samples and `pd2` the current one.
///
/// **Sizing correction vs the design brief**: the brief assumed a `[64]`
/// table indexed `hist*8+cur` (2 indices, weights `[1/4,1/2,1/4]`). The
/// real FFmpeg source uses **3** independent phase-history indices
/// (`pd0`,`pd1`,`pd2`, each 0..7) and weights `0.25/0.5/1.0` (not
/// `0.25/0.5/0.25` -- the newest sample is unweighted, not symmetric),
/// giving a `[8*8*8] = [512]` table indexed `pd0*64 + pd1*8 + pd2` --
/// exactly FFmpeg's own flat indexing convention, kept as-is here so a
/// downstream port of FFmpeg's smoothing call site needs no re-indexing.
fn pd_smooth(ipdopd_cos: &[f32; 8], ipdopd_sin: &[f32; 8]) -> (Vec<f32>, Vec<f32>) {
    let mut re = vec![0f32; 512];
    let mut im = vec![0f32; 512];
    for pd0 in 0..8usize {
        let c0 = f64::from(ipdopd_cos[pd0]);
        let s0 = f64::from(ipdopd_sin[pd0]);
        for pd1 in 0..8usize {
            let c1 = f64::from(ipdopd_cos[pd1]);
            let s1 = f64::from(ipdopd_sin[pd1]);
            for pd2 in 0..8usize {
                let c2 = f64::from(ipdopd_cos[pd2]);
                let s2 = f64::from(ipdopd_sin[pd2]);
                let re_s = 0.25 * c0 + 0.5 * c1 + c2;
                let im_s = 0.25 * s0 + 0.5 * s1 + s2;
                let mag = re_s.hypot(im_s);
                let idx = pd0 * 64 + pd1 * 8 + pd2;
                re[idx] = (re_s / mag) as f32;
                im[idx] = (im_s / mag) as f32;
            }
        }
    }
    (re, im)
}

/// Mirror 7 half-coefficients into the full 13-tap symmetric FIR
/// (`[p6,p5,p4,p3,p2,p1,p0,p1,p2,p3,p4,p5,p6]`, center index 6 = `half[6]`,
/// ps-reference-verbatim.md V4).
fn mirror_proto(half: &[f64; 7]) -> [f64; 13] {
    let mut p = [0f64; 13];
    for (n, pn) in p.iter_mut().enumerate() {
        let k = (6i32 - (n as i32 - 6).abs()) as usize;
        *pn = half[k];
    }
    p
}

/// One modulated complex sub-band filter: `filter[n] = proto[n] *
/// exp(-i*2*pi*(q+0.5)*(n-6)/bands)`, `n=0..12` (ps-reference.md §5 / V4).
fn modulate_one(proto: &[f64; 13], q: usize, bands: usize) -> [[f32; 2]; 13] {
    let mut out = [[0f32; 2]; 13];
    for (n, on) in out.iter_mut().enumerate() {
        let theta = -2.0 * PI * (q as f64 + 0.5) * (n as f64 - 6.0) / bands as f64;
        *on = [
            (proto[n] * theta.cos()) as f32,
            (proto[n] * theta.sin()) as f32,
        ];
    }
    out
}

/// `bands` modulated complex filters from a 7-half-coefficient proto
/// (`HYB_FILT_12`/`HYB_FILT_8`/`HYB_FILT_4`, and the intermediate 8-way
/// split `HYB_FILT_6` is built from -- see [`hyb_filt_6`]).
fn hyb_filt(half: &[f64; 7], bands: usize) -> Vec<[[f32; 2]; 13]> {
    let proto = mirror_proto(half);
    (0..bands).map(|q| modulate_one(&proto, q, bands)).collect()
}

/// `HYB_FILT_6` -- the 20-config QMF-band-0 hybrid split.
///
/// The design brief says "use FFmpeg's direct-6 form"; live-source
/// verification (this task) found that BOTH faad2 (`ps_dec.c`
/// `channel_filter8` + `X[3]+=X[4]; X[2]+=X[5]` merge) and current FFmpeg
/// master (`aacps.c` `hybrid6_cx`, which also merges indices `(2,5)` and
/// `(3,4)` from an 8-way `g0_Q8` split) actually implement the SAME
/// 8-way-then-merge algorithm -- `ps-reference.md`'s "FFmpeg produces 6
/// directly, different from faad2" claim does not hold for current
/// sources. Rather than build a numerically-different naive 6-way
/// modulation (which would NOT reproduce real-decoder output), this
/// pre-merges the FILTER COEFFICIENTS themselves (valid by FIR linearity:
/// summing two sub-band outputs elementwise equals filtering with the
/// summed filter), so downstream code gets a plain 6-tap-set convolution
/// that exactly reproduces the real 8-way+merge decoders' output.
fn hyb_filt_6(half_g0_q8: &[f64; 7]) -> [[[f32; 2]; 13]; 6] {
    let filt8 = hyb_filt(half_g0_q8, 8);
    let add = |a: &[[f32; 2]; 13], b: &[[f32; 2]; 13]| -> [[f32; 2]; 13] {
        let mut r = [[0f32; 2]; 13];
        for n in 0..13 {
            r[n] = [a[n][0] + b[n][0], a[n][1] + b[n][1]];
        }
        r
    };
    [
        filt8[0],
        filt8[1],
        add(&filt8[2], &filt8[5]),
        add(&filt8[3], &filt8[4]),
        filt8[6],
        filt8[7],
    ]
}

/// `DELAY_D[64]` (V5): 14 QMF-slot delay for bands `< 35`, 1 for `>= 35`
/// (faad2 `ps_dec.c`: `short_delay_band = 35`, constant/sample-rate
/// independent in the compiled path -- confirmed by source read).
fn delay_d() -> [u8; 64] {
    let mut d = [0u8; 64];
    for (i, di) in d.iter_mut().enumerate() {
        *di = if i < 35 { 14 } else { 1 };
    }
    d
}

/// One SubQmf `phi_fract` row (FFmpeg `aacps_tablegen.h`, `ps_tableinit`):
/// `theta = -M_PI * fractional_delay_gain * f_center; {cos theta, sin theta}`.
fn phi_fract_row(f_center: f64) -> [f64; 2] {
    let theta = -PI * f64::from(FRACTIONAL_DELAY_GAIN_F32) * f_center;
    [theta.cos(), theta.sin()]
}

/// One SubQmf `Q_fract_allpass` row, the 3 allpass links (FFmpeg
/// `aacps_tablegen.h`): `theta = -M_PI * fractional_delay_links[m] *
/// f_center; {cos theta, sin theta}` for `m = 0..3`.
fn q_fract_allpass_row(f_center: f64) -> [[f64; 2]; 3] {
    let mut r = [[0f64; 2]; 3];
    for (m, rm) in r.iter_mut().enumerate() {
        let theta = -PI * f64::from(FRACTIONAL_DELAY_LINKS_F32[m]) * f_center;
        *rm = [theta.cos(), theta.sin()];
    }
    r
}

/// `PHI_FRACT_SUBQMF20` -- FFmpeg `phi_fract[0][k]` for the hybrid sub-bands
/// (`k < FF_ARRAY_ELEMS(f_center_20) == 10`), `f_center = f_center_20[k] *
/// 0.125`. The consumer array (faad2-shaped) is length 12, but decorrelate
/// only reads the `k < n_hyb == 10` hybrid sub-bands, so indices 10/11 are
/// unused zero padding (FFmpeg's `k >= 10` integer-QMF-centre branch is the
/// separate `PHI_FRACT_QMF` table, out of scope here).
fn phi_fract_subqmf20() -> [[f64; 2]; 12] {
    let mut t = [[0f64; 2]; 12];
    for (k, &fc) in F_CENTER_20_I8.iter().enumerate() {
        t[k] = phi_fract_row(f64::from(fc) * 0.125);
    }
    t
}

/// `PHI_FRACT_SUBQMF34` -- FFmpeg `phi_fract[1][k]`, all 32 hybrid sub-bands
/// (`k < FF_ARRAY_ELEMS(f_center_34) == 32`), `f_center = f_center_34[k] /
/// 24.0`. All 32 entries are real (decorrelate reads `k < n_hyb == 32`).
fn phi_fract_subqmf34() -> [[f64; 2]; 32] {
    let mut t = [[0f64; 2]; 32];
    for (k, &fc) in F_CENTER_34_I8.iter().enumerate() {
        t[k] = phi_fract_row(f64::from(fc) / 24.0);
    }
    t
}

/// `Q_FRACT_ALLPASS_SUBQMF20` -- FFmpeg `Q_fract_allpass[0][k]`, hybrid
/// sub-bands. Length 12; indices 10/11 are unused zero padding (see
/// [`phi_fract_subqmf20`]).
fn q_fract_allpass_subqmf20() -> [[[f64; 2]; 3]; 12] {
    let mut t = [[[0f64; 2]; 3]; 12];
    for (k, &fc) in F_CENTER_20_I8.iter().enumerate() {
        t[k] = q_fract_allpass_row(f64::from(fc) * 0.125);
    }
    t
}

/// `Q_FRACT_ALLPASS_SUBQMF34` -- FFmpeg `Q_fract_allpass[1][k]`, all 32
/// hybrid sub-bands.
fn q_fract_allpass_subqmf34() -> [[[f64; 2]; 3]; 32] {
    let mut t = [[[0f64; 2]; 3]; 32];
    for (k, &fc) in F_CENTER_34_I8.iter().enumerate() {
        t[k] = q_fract_allpass_row(f64::from(fc) / 24.0);
    }
    t
}

