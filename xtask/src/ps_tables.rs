    /// Walks a faad2 binary-tree Huffman table from the root and confirms
    /// it is a well-formed tree: every internal node index is visited
    /// exactly once (no cycles, no unreachable/duplicated nodes) and every
    /// child index is in range.
    fn huff_tree_ok(rows: &[[i8; 2]]) -> bool {
        let mut visited = vec![false; rows.len()];
        fn walk(idx: usize, rows: &[[i8; 2]], visited: &mut [bool]) -> bool {
            if idx >= rows.len() || visited[idx] {
                return false;
            }
            visited[idx] = true;
            for bit in 0..2 {
                let child = rows[idx][bit];
                if child >= 0 && !walk(child as usize, rows, visited) {
                    return false;
                }
            }
            true
        }
        walk(0, rows, &mut visited) && visited.iter().all(|&v| v)
    }

