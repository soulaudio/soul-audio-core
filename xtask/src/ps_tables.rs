/// Build the checked-in table source content.
fn generate() -> String {
    let mut out = String::new();
    // The wired PS pipeline consumes every table below, so there is no blanket
    // module `#![allow(dead_code)]`. A handful of scalar constants
    // (`ICC_INVQ`/`G0_Q*`/`DECAY_SLOPE`/... — the raw ISO reference values) are
    // emitted only so the generated self-check test can anchor the derived
    // tables against them; the runtime re-derives its own working copies. Those
    // few carry a *targeted* `#[allow(dead_code)]` at their emission site
    // (below), never a blanket module allow.
    // Machine-generated literals legitimately hit named math constants at a
    // few indices (e.g. 0.70710678 = 1/sqrt(2), asserted by the mandated
    // self-check test below) and carry full f64-derived precision when
    // rendered -- both expected for a generated table file + its test.
    // `useless_conversion`: the mandated self-check test (task-1-brief.md,
    // embedded byte-for-byte below) calls `f64::from(FILTER_A[0])`, and
    // FILTER_A is `f64` (not f32, see `lit64`'s doc) so that conversion is
    // syntactically a no-op -- required by the fixed test text, not a bug.
    out.push_str(
        "#![allow(\n    clippy::excessive_precision,\n    clippy::unreadable_literal,\n    clippy::useless_conversion,\n    clippy::approx_constant\n)]\n",
    );
    out.push_str("// @generated by `cargo xtask gen-ps-tables` -- do not edit.\n");
    out.push_str("// PS const tables (Huffman/dequant/band-maps/hybrid-FIR/allpass).\n");
    out.push_str("// See xtask/src/ps_tables.rs for layout/conventions/provenance.\n");
    out.push_str("use super::Cpx;\n\n");

    // ---- V1 Huffman trees ----
    emit_i8_pairs("F_HUFF_IID_DEF", &F_HUFF_IID_DEF_I8, &mut out);
    emit_i8_pairs("T_HUFF_IID_DEF", &T_HUFF_IID_DEF_I8, &mut out);
    emit_i8_pairs("F_HUFF_IID_FINE", &F_HUFF_IID_FINE_I8, &mut out);
    emit_i8_pairs("T_HUFF_IID_FINE", &T_HUFF_IID_FINE_I8, &mut out);
    emit_i8_pairs("F_HUFF_ICC", &F_HUFF_ICC_I8, &mut out);
    emit_i8_pairs("T_HUFF_ICC", &T_HUFF_ICC_I8, &mut out);
    emit_i8_pairs("F_HUFF_IPD", &F_HUFF_IPD_I8, &mut out);
    emit_i8_pairs("T_HUFF_IPD", &T_HUFF_IPD_I8, &mut out);
    emit_i8_pairs("F_HUFF_OPD", &F_HUFF_OPD_I8, &mut out);
    emit_i8_pairs("T_HUFF_OPD", &T_HUFF_OPD_I8, &mut out);

    // ---- V2.a IID dequant ----
    let sf_iid_normal: Vec<f32> = SF_IID_NORMAL_F64.iter().map(|&v| v as f32).collect();
    let sf_iid_fine: Vec<f32> = SF_IID_FINE_F64.iter().map(|&v| v as f32).collect();
    emit_f32_1d("SF_IID_NORMAL", &sf_iid_normal, &mut out);
    emit_f32_1d("SF_IID_FINE", &sf_iid_fine, &mut out);

    // ---- V2.b ICC dequant + mixing alpha ----
    let icc_invq: Vec<f32> = ICC_INVQ_F64.iter().map(|&v| v as f32).collect();
    let cos_alphas: Vec<f32> = COS_ALPHAS_F64.iter().map(|&v| v as f32).collect();
    let sin_alphas: Vec<f32> = SIN_ALPHAS_F64.iter().map(|&v| v as f32).collect();
    // `ICC_INVQ` is a self-check anchor only: the runtime mixes via the derived
    // `COS_ALPHAS`/`SIN_ALPHAS`, never the raw inverse-quant values.
    out.push_str("#[allow(dead_code)]\n");
    emit_f32_1d("ICC_INVQ", &icc_invq, &mut out);
    emit_f32_1d("COS_ALPHAS", &cos_alphas, &mut out);
    emit_f32_1d("SIN_ALPHAS", &sin_alphas, &mut out);

    // ---- V2.c IPD/OPD angle + atan2-free complex smoothing (computed) ----
    let (ipdopd_cos, ipdopd_sin) = ipdopd_cos_sin();
    emit_f32_1d("IPDOPD_COS", &ipdopd_cos, &mut out);
    emit_f32_1d("IPDOPD_SIN", &ipdopd_sin, &mut out);
    let (pd_re, pd_im) = pd_smooth(&ipdopd_cos, &ipdopd_sin);
    emit_f32_1d("PD_RE_SMOOTH", &pd_re, &mut out);
    emit_f32_1d("PD_IM_SMOOTH", &pd_im, &mut out);

    // ---- V2.d Type-B/beta/gamma mixing-optimization tables ----
    fn conv2d(t: &[[f64; 8]]) -> Vec<Vec<f32>> {
        t.iter()
            .map(|r| r.iter().map(|&v| v as f32).collect())
            .collect()
    }
    emit_f32_2d("COS_BETAS_NORMAL", &conv2d(&COS_BETAS_NORMAL_F64), &mut out);
    emit_f32_2d("SIN_BETAS_NORMAL", &conv2d(&SIN_BETAS_NORMAL_F64), &mut out);
    emit_f32_2d("COS_BETAS_FINE", &conv2d(&COS_BETAS_FINE_F64), &mut out);
    emit_f32_2d("SIN_BETAS_FINE", &conv2d(&SIN_BETAS_FINE_F64), &mut out);
    emit_f32_2d(
        "SINCOS_ALPHAS_B_NORMAL",
        &conv2d(&SINCOS_ALPHAS_B_NORMAL_F64),
        &mut out,
    );
    emit_f32_2d(
        "SINCOS_ALPHAS_B_FINE",
        &conv2d(&SINCOS_ALPHAS_B_FINE_F64),
        &mut out,
    );
    emit_f32_2d(
        "COS_GAMMAS_NORMAL",
        &conv2d(&COS_GAMMAS_NORMAL_F64),
        &mut out,
    );
    emit_f32_2d("COS_GAMMAS_FINE", &conv2d(&COS_GAMMAS_FINE_F64), &mut out);
    emit_f32_2d(
        "SIN_GAMMAS_NORMAL",
        &conv2d(&SIN_GAMMAS_NORMAL_F64),
        &mut out,
    );
    emit_f32_2d("SIN_GAMMAS_FINE", &conv2d(&SIN_GAMMAS_FINE_F64), &mut out);

    // ---- V3 flattened band maps ----
    emit_u8_1d("FF_K_TO_I_20", &FF_K_TO_I_20_U8, &mut out);
    emit_u8_1d("FF_K_TO_I_34", &FF_K_TO_I_34_U8, &mut out);

    // ---- V4 hybrid FIR protos + modulated complex filters ----
    // The raw `G*` prototype filters are self-check anchors only: the runtime
    // convolves with the pre-modulated `HYB_FILT_*` matrices below (and the
    // 20-config's 8-tap `g0_Q8` is pre-merged into the 6-band `HYB_FILT_6`, so
    // no `G0_Q8` static is emitted at all — its f64 source still feeds
    // `hyb_filt_6` here).
    let g0_q12: Vec<f32> = G0_Q12_F64.iter().map(|&v| v as f32).collect();
    let g1_q8: Vec<f32> = G1_Q8_F64.iter().map(|&v| v as f32).collect();
    let g2_q4: Vec<f32> = G2_Q4_F64.iter().map(|&v| v as f32).collect();
    out.push_str("#[allow(dead_code)]\n");
    emit_f32_1d("G0_Q12", &g0_q12, &mut out);
    out.push_str("#[allow(dead_code)]\n");
    emit_f32_1d("G1_Q8", &g1_q8, &mut out);
    out.push_str("#[allow(dead_code)]\n");
    emit_f32_1d("G2_Q4", &g2_q4, &mut out);

    emit_cpx_2d13("HYB_FILT_12", &hyb_filt(&G0_Q12_F64, 12), &mut out);
    emit_cpx_2d13("HYB_FILT_8", &hyb_filt(&G1_Q8_F64, 8), &mut out);
    emit_cpx_2d13("HYB_FILT_4", &hyb_filt(&G2_Q4_F64, 4), &mut out);
    emit_cpx_2d13("HYB_FILT_6", &hyb_filt_6(&G0_Q8_F64), &mut out);

    // ---- V5 allpass / decorrelation phase tables ----
    // f64 (not f32, unlike every other table here): see `lit64`'s doc --
    // the mandated self-check test needs 1e-9 precision on FILTER_A[0].
    emit_f64_1d("FILTER_A", &FILTER_A_F64, &mut out);
    emit_u8_1d("NUM_SAMPLE_DELAY_SER", &NUM_SAMPLE_DELAY_SER_U8, &mut out);
    emit_u8_1d("DELAY_D", &delay_d(), &mut out);

    fn conv_cpx1d(t: &[[f64; 2]]) -> Vec<[f32; 2]> {
        t.iter().map(|p| [p[0] as f32, p[1] as f32]).collect()
    }
    emit_cpx_1d("PHI_FRACT_QMF", &conv_cpx1d(&PHI_FRACT_QMF_F64), &mut out);
    emit_cpx_1d(
        "PHI_FRACT_SUBQMF20",
        &conv_cpx1d(&phi_fract_subqmf20()),
        &mut out,
    );
    emit_cpx_1d(
        "PHI_FRACT_SUBQMF34",
        &conv_cpx1d(&phi_fract_subqmf34()),
        &mut out,
    );

    fn conv_cpx2d3(t: &[[[f64; 2]; 3]]) -> Vec<[[f32; 2]; 3]> {
        t.iter()
            .map(|row| {
                let mut r = [[0f32; 2]; 3];
                for i in 0..3 {
                    r[i] = [row[i][0] as f32, row[i][1] as f32];
                }
                r
            })
            .collect()
    }
    emit_cpx_2d3(
        "Q_FRACT_ALLPASS_QMF",
        &conv_cpx2d3(&Q_FRACT_ALLPASS_QMF_F64),
        &mut out,
    );
    emit_cpx_2d3(
        "Q_FRACT_ALLPASS_SUBQMF20",
        &conv_cpx2d3(&q_fract_allpass_subqmf20()),
        &mut out,
    );
    emit_cpx_2d3(
        "Q_FRACT_ALLPASS_SUBQMF34",
        &conv_cpx2d3(&q_fract_allpass_subqmf34()),
        &mut out,
    );

    // ---- V6 config constants ----
    out.push_str("pub(super) static NUM_ENV_TAB: [[u8; 4]; 2] = [[0, 1, 2, 4], [1, 2, 3, 4]];\n");
    out.push_str("pub(super) static NR_IIDICC_PAR_TAB: [u8; 6] = [10, 20, 34, 10, 20, 34];\n");
    out.push_str("pub(super) static NR_IIDOPD_PAR_TAB: [u8; 6] = [5, 11, 17, 5, 11, 17];\n");
    // Decorrelation/mix scalar anchors: the runtime (`decorrelate`/`mix`) keeps
    // its own local copies of these, so the emitted constants exist only for the
    // generated self-check test — a targeted `#[allow(dead_code)]` each.
    out.push_str("#[allow(dead_code)]\npub(super) const DECAY_SLOPE: f32 = 0.05;\n");
    out.push_str("#[allow(dead_code)]\npub(super) const ALPHA_DECAY: f32 = 0.76592833836465;\n");
    out.push_str("#[allow(dead_code)]\npub(super) const ALPHA_SMOOTH: f32 = 0.25;\n");
    out.push_str("#[allow(dead_code)]\npub(super) const GAMMA: f32 = 1.5;\n");
    out.push_str("#[allow(dead_code)]\npub(super) const NEGATE_IPD_MASK: u16 = 0x1000;\n");

    out.push_str(TEST_MODULE);
    out.push_str(MORE_TESTS);
    out
}

/// Regenerate the checked-in table source file.
pub fn run() -> Result<(), String> {
    let content = generate();
    std::fs::write(TABLES_PATH, content).map_err(|e| format!("writing {TABLES_PATH}: {e}"))
}

/// CI guard: fail if the committed tables differ from a fresh generation.
pub fn check() -> Result<(), String> {
    let want = generate();
    let have =
        std::fs::read_to_string(TABLES_PATH).map_err(|e| format!("reading {TABLES_PATH}: {e}"))?;
    if want == have {
        Ok(())
    } else {
        Err(format!(
            "{TABLES_PATH} is stale -- run `cargo xtask gen-ps-tables`"
        ))
    }
}

