/// Shortest round-tripping f32 literal, guaranteed to parse as a float
/// (`{v}` renders whole values as bare integers, which Rust rejects as
/// float elements -- append `.0` when there is no `.`/`e` already).
fn lit(v: f32) -> String {
    let s = format!("{v}");
    if s.contains(['.', 'e', 'E']) {
        s
    } else {
        format!("{s}.0")
    }
}

fn cpx_lit(v: [f32; 2]) -> String {
    format!("Cpx{{re:{},im:{}}}", lit(v[0]), lit(v[1]))
}

/// Shortest round-tripping f64 literal (see [`lit`]). Used only for
/// `FILTER_A`: the brief's mandated self-check test compares it against a
/// full-precision f64 anchor with a `1e-9` tolerance, which an `f32`
/// round-trip cannot reach (f32 has ~7 significant digits; the same
/// precision gap the sbr_tables.rs V_NOISE self-check documents) -- an
/// `f32` table failed that exact assertion during TDD (see
/// ps-task-1-report.md), so `FILTER_A` is `[f64; 3]`, not `[f32; 3]`.
fn lit64(v: f64) -> String {
    let s = format!("{v}");
    if s.contains(['.', 'e', 'E']) {
        s
    } else {
        format!("{s}.0")
    }
}

fn emit_f64_1d(name: &str, t: &[f64], out: &mut String) {
    writeln!(out, "#[rustfmt::skip]").unwrap();
    writeln!(out, "pub(super) static {name}: [f64; {}] = [", t.len()).unwrap();
    for chunk in t.chunks(8) {
        out.push_str("    ");
        for v in chunk {
            write!(out, "{},", lit64(*v)).unwrap();
        }
        out.push('\n');
    }
    out.push_str("];\n");
}

