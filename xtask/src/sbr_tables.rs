/// Build the checked-in table source content.
fn generate() -> String {
    let mut out = String::new();
    // No blanket `dead_code` allow: every table below (QMF_PROTO/QMF_ANA_*/
    // QMF_SYN_*/V_NOISE/LOG2_INT/POW2_FRAC) is consumed by qmf.rs/hfadj.rs/
    // freq_tables.rs now that SBR is fully wired (T11); `check-sbr-tables`
    // (which diffs this generator's output against the checked-in file)
    // will catch drift if a future table stops being consumed and needs the
    // allow back.
    // LOG2_INT/POW2_FRAC are computed tables that legitimately land exactly on
    // a few named math constants at some indices (e.g. log2(10), 2^0.5) --
    // clippy's approx_constant lint would otherwise flag those generated
    // entries as if they were hand-typed decimal approximations.
    out.push_str("#![allow(clippy::approx_constant)]\n");
    // The self-check tests below compare against full-precision f64 reference
    // anchors (typed f32 in an f32 context) and index the small LOG2/POW2 tables
    // by range on purpose (index-for-index correspondence) -- both fine for a
    // machine-generated table+self-check file.
    out.push_str("#![allow(clippy::excessive_precision, clippy::needless_range_loop)]\n");
    out.push_str("// @generated by `cargo xtask gen-sbr-tables` -- do not edit.\n");
    out.push_str("// SBR const tables (QMF prototype/modulation, noise, log2/pow2).\n");
    out.push_str("// See xtask/src/sbr_tables.rs for layout/conventions/provenance.\n");

    emit("QMF_PROTO", &qmf_proto_f32(), &mut out);

    let (ana_cos, ana_sin) = qmf_analysis_modulation();
    emit2d("QMF_ANA_COS", &ana_cos, &mut out);
    emit2d("QMF_ANA_SIN", &ana_sin, &mut out);

    let (syn_cos, syn_sin) = qmf_synthesis_modulation();
    emit2d("QMF_SYN_COS", &syn_cos, &mut out);
    emit2d("QMF_SYN_SIN", &syn_sin, &mut out);

    emit_pairs("V_NOISE", &v_noise_f32(), &mut out);

    emit("LOG2_INT", &log2_int(), &mut out);
    emit("POW2_FRAC", &pow2_frac(), &mut out);

    out.push_str(TEST_MODULE);
    out
}

/// Regenerate the checked-in table source file.
pub fn run() -> Result<(), String> {
    let content = generate();
    std::fs::write(TABLES_PATH, content).map_err(|e| format!("writing {TABLES_PATH}: {e}"))
}

/// CI guard: fail if the committed tables differ from a fresh generation.
pub fn check() -> Result<(), String> {
    let want = generate();
    let have =
        std::fs::read_to_string(TABLES_PATH).map_err(|e| format!("reading {TABLES_PATH}: {e}"))?;
    if want == have {
        Ok(())
    } else {
        Err(format!(
            "{TABLES_PATH} is stale -- run `cargo xtask gen-sbr-tables`"
        ))
    }
}

