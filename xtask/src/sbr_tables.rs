/// Analysis QMF modulation, `cos/sin(pi*(k+0.5)*(2n-0.5)/64)`, `k=0..31`,
/// `n=0..63` (ISO 4.6.18.4 / `sbr-reference.md` section 7.1).
///
/// The `-0.5` offset (form `2n-0.5`) is FFmpeg's/faad2's exact absolute phase
/// convention for `X_low`. It was DERIVED from source, not guessed: faad2's
/// high-quality complex analysis (`sbr_qmf_analysis_32`: window+fold to `u[n]`,
/// then a reorder → `dct4_kernel` → reorder) produces, on the SAME `u[n]` our
/// [`qmf::qmf_analysis`] computes, the exact matrix
/// `X[k] = 2·Σ_n u[n]·exp(+i·pi·(k+0.5)·(2n-0.5)/64)` (magnitude 2.0, phase
/// linear in `n` with offset `0.5`, verified to ~2e-7 across all `k,n`).
///
/// This is a per-band **absolute phase** convention, not just a group delay.
/// Earlier offsets (`-95`, then `-96.5`) form a *self-consistent* pair with a
/// matching synthesis (the QMF round-trip and the frequency/amplitude
/// localization tests pass — none pin absolute phase), and they even match
/// FFmpeg on the low-band pass-through (the analysis/synthesis per-band phases
/// cancel there). But SBR HF generation *copies* `X_low[p]` (source band `p`)
/// up to a high band `k`, and the ISO patch semantics are only correct in
/// FFmpeg's phase convention. With a mismatched convention the reconstructed
/// high band carries `phi_k^syn · phi_p^ana` (a phase set by BOTH the source
/// band `p` and target band `k`), decorrelating it from FFmpeg's — exactly the
/// "high-band shape wrong, error grows with frequency" conformance failure.
/// Fixing analysis **and** synthesis (see [`qmf_synthesis_modulation`]) to
/// FFmpeg's exact convention drives both per-band phases to 1.
fn qmf_analysis_modulation() -> (Vec<Vec<f32>>, Vec<Vec<f32>>) {
    let mut c = vec![vec![0f32; 64]; 32];
    let mut s = vec![vec![0f32; 64]; 32];
    for (k, (crow, srow)) in c.iter_mut().zip(s.iter_mut()).enumerate() {
        for n in 0..64usize {
            let a = PI * (k as f64 + 0.5) * (2.0 * n as f64 - 0.5) / 64.0;
            crow[n] = a.cos() as f32;
            srow[n] = a.sin() as f32;
        }
    }
    (c, s)
}

/// Synthesis QMF modulation, `-cos/-sin(pi*(k+0.5)*(2n+1)/128)`, `n=0..127`,
/// `k=0..63` (section 7.2). Outer index is `n` (128), inner is `k` (64) --
/// matches the runtime self-check and downstream `qmf.rs`.
///
/// Like [`qmf_analysis_modulation`], DERIVED from faad2's high-quality complex
/// synthesis (`sbr_qmf_synthesis_64`: two `dct4_kernel`s + butterfly into the
/// `v` ring, then the shared windowed overlap-add [`qmf.rs`] already does). On
/// the SAME 64 complex bands, faad2's modulation of `X[k]` into the 128 real
/// pre-window samples is exactly `w[n] = Re{ Σ_k X[k]·(-exp(+i·pi·(k+0.5)·
/// (2n+1)/128)) }` — i.e. offset `2n+1` (not `2n-63`) and a **global sign
/// flip** (verified to ~2e-7 across all `n,k`), hence the negated `cos`/`sin`.
/// The old `+cos/+sin(2n-63)` was a valid round-trip partner of the old
/// analysis but not FFmpeg's convention; both banks must match FFmpeg together
/// so the SBR high band (which reuses `X_low`'s absolute phase) reconstructs.
fn qmf_synthesis_modulation() -> (Vec<Vec<f32>>, Vec<Vec<f32>>) {
    let mut c = vec![vec![0f32; 64]; 128];
    let mut s = vec![vec![0f32; 64]; 128];
    for (n, (crow, srow)) in c.iter_mut().zip(s.iter_mut()).enumerate() {
        for k in 0..64usize {
            let a = PI * (k as f64 + 0.5) * (2.0 * n as f64 + 1.0) / 128.0;
            crow[k] = -(a.cos() as f32);
            srow[k] = -(a.sin() as f32);
        }
    }
    (c, s)
}

/// `log2(i)`, `i=0..64`; `[0]` is unused by section 3.3 (it only ever looks up
/// `log2(k1/k0)` with `k1,k0 >= 1`) but stored as `0.0` rather than `-inf` so
/// the const array stays a plain finite `f32` table.
fn log2_int() -> Vec<f32> {
    (0..65usize)
        .map(|i| {
            if i == 0 {
                0.0
            } else {
                (i as f64).log2() as f32
            }
        })
        .collect()
}

/// `2^(i/256)`, `i=0..256` inclusive (257 entries) -- the fractional part of
/// section 3.3's geometric spacing `2^x = 2^floor(x) * POW2_FRAC[round(frac(x)*256)]`.
fn pow2_frac() -> Vec<f32> {
    (0..=256usize)
        .map(|i| 2f64.powf(i as f64 / 256.0) as f32)
        .collect()
}

/// Shortest round-tripping f32 literal, guaranteed to parse in an `[f32; _]`
/// array -- `{v}` renders whole values as bare integers (`1`, `0`), which Rust
/// rejects as float elements, so append `.0` when there is no `.`/`e` already.
fn lit(v: f32) -> String {
    let s = format!("{v}");
    if s.contains(['.', 'e', 'E']) {
        s
    } else {
        format!("{s}.0")
    }
}

fn emit(name: &str, t: &[f32], out: &mut String) {
    writeln!(out, "#[rustfmt::skip]").unwrap();
    writeln!(out, "pub(super) static {name}: [f32; {}] = [", t.len()).unwrap();
    for chunk in t.chunks(8) {
        out.push_str("    ");
        for v in chunk {
            write!(out, "{},", lit(*v)).unwrap();
        }
        out.push('\n');
    }
    out.push_str("];\n");
}

/// Same as [`emit`] for a rectangular `outer x inner` table (`Vec<Vec<f32>>`,
/// every row the same length) -- one source-array row per output line.
fn emit2d(name: &str, t: &[Vec<f32>], out: &mut String) {
    let outer = t.len();
    let inner = t.first().map_or(0, Vec::len);
    writeln!(out, "#[rustfmt::skip]").unwrap();
    writeln!(
        out,
        "pub(super) static {name}: [[f32; {inner}]; {outer}] = ["
    )
    .unwrap();
    for row in t {
        out.push_str("    [");
        for v in row {
            write!(out, "{},", lit(*v)).unwrap();
        }
        out.push_str("],\n");
    }
    out.push_str("];\n");
}

/// Same as [`emit`] for `[re, im]` pairs (`V_NOISE`), 4 pairs per line.
fn emit_pairs(name: &str, t: &[[f32; 2]], out: &mut String) {
    writeln!(out, "#[rustfmt::skip]").unwrap();
    writeln!(out, "pub(super) static {name}: [[f32; 2]; {}] = [", t.len()).unwrap();
    for chunk in t.chunks(4) {
        out.push_str("    ");
        for v in chunk {
            write!(out, "[{},{}],", lit(v[0]), lit(v[1])).unwrap();
        }
        out.push('\n');
    }
    out.push_str("];\n");
}

