//! Generates `crates/soul-audio-core/src/formats/aac/sbr/tables.rs` — every
//! transcendental/const table the SBR (Spectral Band Replication) decoder
//! needs: the shared 640-tap QMF prototype filter, the 32×64 analysis and
//! 128×64 synthesis QMF modulation cos/sin tables, the 512-entry pseudo-random
//! noise table, and the `log2`/`pow2` tables §3.3's geometric frequency-band
//! spacing needs. Run via `cargo xtask gen-sbr-tables`; the output is checked
//! in and CI-guarded by [`check`] (wired into `xtask verify`), exactly like
//! the filterbank tables.
//!
//! The core crate is `#![no_std]`, no-alloc, and its dependency allowlist
//! forbids `libm`, so SBR (like the AAC-LC filterbank before it) cannot call
//! `cos`/`sin`/`log2`/`powf` at runtime — every transcendental value the SBR
//! decoder needs is baked here (host-side, where `f64` trig is fine) and read
//! from `const`/`static` tables. A runtime self-check test embedded in the
//! generated `sbr/tables.rs` re-derives the closed-form values (`std` trig is
//! fine in `#[cfg(test)]`) so the tables can't silently rot.
//!
//! # Verbatim vs computed
//! `QMF_PROTO_F64` and `V_NOISE_F64` below are transcribed VERBATIM from
//! `.superpowers/sdd/sbr-reference-verbatim.md` §1/§2 (NOT recomputed — see
//! that file's provenance note) and re-emitted as `f32`; [`tests`] below
//! re-checks their anchors so a bad paste fails host-side too. Every other
//! table is computed host-side from the closed-form formulas in
//! `.superpowers/sdd/sbr-reference.md` §3.3/§7.
//!
//! # Layout / conventions (must match downstream `qmf.rs`/`freq_tables.rs`)
//! - `QMF_PROTO[i]` — the 640-tap prototype window (ISO Table 4.A.87), shared
//!   by the 32-band analysis and 64-band synthesis QMF (used with a stride).
//! - `QMF_ANA_COS/SIN[k][n] = cos/sin(π·(k+0.5)·(2n−0.5)/64)`, `k=0..31`,
//!   `n=0..63` — analysis modulation (ISO 4.6.18.4, `sbr-reference.md` §7.1).
//!   The `−0.5` offset is FFmpeg's/faad2's exact absolute-phase convention for
//!   `X_low`, derived from source; see [`qmf_analysis_modulation`].
//! - `QMF_SYN_COS/SIN[n][k] = −cos/−sin(π·(k+0.5)·(2n+1)/128)`, `n=0..127`,
//!   `k=0..63` — synthesis modulation (§7.2), also FFmpeg/faad2 exact (offset
//!   `2n+1`, global sign flip). Note the index order: outer `n` (128), inner
//!   `k` (64).
//! - `V_NOISE[i] = [re, im]` — the ISO Table 1.A.13 pseudo-random noise
//!   sequence, walked by a running index masked to 0..511 (§9.4).
//! - `LOG2_INT[i] = log2(i)`, `i=0..64` (`[0]` unused, stored as `0.0`).
//! - `POW2_FRAC[i] = 2^(i/256)`, `i=0..256` — with `LOG2_INT`, gives §3.3's
//!   geometric frequency-band spacing without `libm`
//!   (`2^x = 2^floor(x) · POW2_FRAC[round(frac(x)·256)]`).

