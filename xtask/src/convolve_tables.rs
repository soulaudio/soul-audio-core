//! Generates `crates/soul-audio-core/src/dsp/convolve_tables.rs` — the
//! convolution engine's radix-2 FFT twiddle table. Run via
//! `cargo xtask gen-convolve-tables`; the output is checked in and CI-guarded
//! by [`check`] (wired into `xtask verify`), exactly like the filterbank and
//! resampler tables.
//!
//! The core crate is `#![no_std]`, no-alloc, and its dependency allowlist
//! forbids `libm`, so it cannot call `sin`/`cos` at runtime — the twiddles the
//! partitioned convolver's FFT needs are baked here (host-side, in `f64`) and
//! read from a `const` table. A runtime self-check in `dsp::convolve` re-derives
//! the closed-form properties (unit modulus, the quarter-turn identities) so the
//! table cannot silently rot.
//!
//! The AAC filterbank has its own copy of an equivalent table: it is
//! feature-gated behind `aac` and private to that codec, and the convolver must
//! work in a build without it — a shared table would couple a patent-gated codec
//! to the DSP chain.
//!
//! # Layout / conventions (must match `dsp::convolve`)
//! - `FFT_TW_COS/SIN[m] = cos/sin(2π·m/FFT_N)`, `m = 0..FFT_N/2`. A length-`len`
//!   sub-DFT's column-`j` twiddle is index `j·(FFT_N/len)`, always `< FFT_N/2`
//!   for every `len <= FFT_N`: forward uses `(cos, −sin)`, inverse `(cos, +sin)`.
//!   One table therefore serves every transform size up to `FFT_N`.
//! - `FFT_N` is the convolver's partition transform size: twice its partition
//!   length, so a partition's linear convolution fits without time-domain
//!   aliasing.

use std::f64::consts::PI;
use std::fmt::Write as _;

const TABLES_PATH: &str = "crates/soul-audio-core/src/dsp/convolve_tables.rs";

/// The convolver's FFT size — twice [`PARTITION`](self::PARTITION_DOC) (256),
/// so each zero-padded partition's linear convolution fits. Must equal
/// `dsp::convolve::FFT_N`.
const FFT_N: usize = 512;

/// Radix-2 FFT twiddles `cos/sin(2π·m/FFT_N)`, `m = 0..FFT_N/2`.
fn fft_twiddles() -> (Vec<f32>, Vec<f32>) {
    let n = FFT_N / 2;
    let mut c = vec![0f32; n];
    let mut s = vec![0f32; n];
    for m in 0..n {
        let a = 2.0 * PI * m as f64 / FFT_N as f64;
        c[m] = a.cos() as f32;
        s[m] = a.sin() as f32;
    }
    (c, s)
}

/// Shortest round-tripping f32 literal, guaranteed to parse in an `[f32; _]`
/// array — `{v}` renders whole values as bare integers (`1`, `0`), which Rust
/// rejects as float elements, so append `.0` when there's no `.`/`e` already.
fn lit(v: f32) -> String {
    let s = format!("{v}");
    if s.contains(['.', 'e', 'E']) {
        s
    } else {
        format!("{s}.0")
    }
}

fn emit(name: &str, t: &[f32], out: &mut String) {
    writeln!(out, "#[rustfmt::skip]").unwrap();
    writeln!(out, "pub(super) static {name}: [f32; {}] = [", t.len()).unwrap();
    for chunk in t.chunks(8) {
        out.push_str("    ");
        for v in chunk {
            write!(out, "{},", lit(*v)).unwrap();
        }
        out.push('\n');
    }
    out.push_str("];\n");
}

/// Build the checked-in table source content.
fn generate() -> String {
    let mut out = String::new();
    out.push_str("// @generated by `cargo xtask gen-convolve-tables` — do not edit.\n");
    out.push_str("// Radix-2 FFT twiddles for the partitioned convolution engine.\n");
    out.push_str("// See xtask/src/convolve_tables.rs for layout/conventions.\n");
    let (c, s) = fft_twiddles();
    emit("FFT_TW_COS", &c, &mut out);
    emit("FFT_TW_SIN", &s, &mut out);
    out
}

/// Regenerate the checked-in table source file.
pub fn run() -> Result<(), String> {
    let content = generate();
    std::fs::write(TABLES_PATH, content).map_err(|e| format!("writing {TABLES_PATH}: {e}"))
}

/// CI guard: fail if the committed tables differ from a fresh generation.
pub fn check() -> Result<(), String> {
    let want = generate();
    let have =
        std::fs::read_to_string(TABLES_PATH).map_err(|e| format!("reading {TABLES_PATH}: {e}"))?;
    if want == have {
        Ok(())
    } else {
        Err(format!(
            "{TABLES_PATH} is stale — run `cargo xtask gen-convolve-tables`"
        ))
    }
}

/// Doc anchor for the partition length the FFT size is derived from (the real
/// constant lives in `dsp::convolve`; this keeps the two documented together).
#[allow(dead_code)]
const PARTITION_DOC: usize = FFT_N / 2;
