//! Generates `crates/soul-audio-core/src/resample_tables.rs` — Kaiser-windowed
//! sinc prototype tables for the resampler, in the **libsamplerate** layout:
//! a single oversampled *half* of the (symmetric) prototype, walked by the kernel
//! with a ratio-scaled increment so the cutoff and effective tap count adapt to
//! the conversion ratio (this is what lets one const table anti-alias
//! downsampling without runtime filter design). Run via
//! `cargo xtask gen-resample-tables`; the output is checked in and CI-guarded.
//!
//! For each tier: `L` = samples per input-sample (oversampling), `Z` = half the
//! number of zero crossings, `HALF = L*Z`. `SINC[j]` (j in 0..=HALF) is
//! `window(j/HALF) · fc · sinc(fc · j/L)`, normalized so the unity-ratio DC gain
//! is exactly 1. The kernel reconstructs an output as a two-sided walk over the
//! input, indexing `SINC` at `distance · L · min(1, out/in)` and interpolating
//! linearly between adjacent entries.

use std::f64::consts::PI;
use std::fmt::Write as _;

fn i0(x: f64) -> f64 {
    let mut sum = 1.0;
    let mut term = 1.0;
    let half = x / 2.0;
    for k in 1..80 {
        term *= (half / k as f64) * (half / k as f64);
        sum += term;
        if term < 1e-15 * sum {
            break;
        }
    }
    sum
}

fn sinc(x: f64) -> f64 {
    if x == 0.0 {
        1.0
    } else {
        (PI * x).sin() / (PI * x)
    }
}

/// Build the half-prototype `SINC[0..=half]` for one tier, DC-normalized.
fn proto(l: usize, z: usize, fc: f64, beta: f64) -> Vec<f32> {
    let half = l * z;
    let denom = i0(beta);
    let mut t = vec![0f64; half + 1];
    for (j, v) in t.iter_mut().enumerate() {
        let r = j as f64 / half as f64; // 0..1 across the half-window
        let win = i0(beta * (1.0 - r * r).max(0.0).sqrt()) / denom;
        *v = win * fc * sinc(fc * j as f64 / l as f64);
    }
    // Unity-ratio DC gain = SINC[0] + 2·Σ_{m≥1} SINC[m·L]. Normalize it to 1.
    let mut s = t[0];
    let mut m = l;
    while m <= half {
        s += 2.0 * t[m];
        m += l;
    }
    for v in &mut t {
        *v /= s;
    }
    t.iter().map(|&x| x as f32).collect()
}

fn emit_arr(name: &str, t: &[f32], out: &mut String) {
    writeln!(out, "#[rustfmt::skip]").unwrap();
    writeln!(out, "pub(crate) static {name}: [f32; {}] = [", t.len()).unwrap();
    for chunk in t.chunks(8) {
        out.push_str("    ");
        for v in chunk {
            // Shortest round-tripping f32 literal (no excessive precision).
            write!(out, "{v},").unwrap();
        }
        out.push('\n');
    }
    out.push_str("];\n");
}

const TABLES_PATH: &str = "crates/soul-audio-core/src/resample_tables.rs";

/// Regenerate the coefficient-table source file.
pub fn run() -> Result<(), String> {
    let content = generate();
    std::fs::write(TABLES_PATH, content).map_err(|e| format!("writing {TABLES_PATH}: {e}"))
}

/// CI guard: fail if the committed tables differ from a fresh generation.
pub fn check() -> Result<(), String> {
    let want = generate();
    let have =
        std::fs::read_to_string(TABLES_PATH).map_err(|e| format!("reading {TABLES_PATH}: {e}"))?;
    if want == have {
        Ok(())
    } else {
        Err(format!(
            "{TABLES_PATH} is stale — run `cargo xtask gen-resample-tables`"
        ))
    }
}

/// Build the coefficient-table source content.
fn generate() -> String {
    // (L oversampling, Z half zero-crossings, cutoff fc, Kaiser beta)
    let (fast_l, fast_z, fast_fc, fast_beta) = (64usize, 16usize, 0.90, 9.0);
    let (hq_l, hq_z, hq_fc, hq_beta) = (128usize, 32usize, 0.95, 12.5);

    let mut out = String::new();
    out.push_str("// @generated by `cargo xtask gen-resample-tables` — do not edit.\n");
    out.push_str("// Kaiser-windowed sinc prototypes (libsamplerate layout). Params:\n");
    writeln!(
        out,
        "//   FAST: L={fast_l} Z={fast_z} cutoff={fast_fc} beta={fast_beta}"
    )
    .unwrap();
    writeln!(
        out,
        "//   HQ:   L={hq_l} Z={hq_z} cutoff={hq_fc} beta={hq_beta}"
    )
    .unwrap();
    writeln!(out, "pub(crate) const FAST_L: usize = {fast_l};").unwrap();
    writeln!(
        out,
        "pub(crate) const FAST_HALF: usize = {};",
        fast_l * fast_z
    )
    .unwrap();
    writeln!(out, "pub(crate) const HQ_L: usize = {hq_l};").unwrap();
    writeln!(out, "pub(crate) const HQ_HALF: usize = {};", hq_l * hq_z).unwrap();
    emit_arr(
        "FAST_SINC",
        &proto(fast_l, fast_z, fast_fc, fast_beta),
        &mut out,
    );
    emit_arr("HQ_SINC", &proto(hq_l, hq_z, hq_fc, hq_beta), &mut out);
    out
}
