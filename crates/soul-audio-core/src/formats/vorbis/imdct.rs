//! Vorbis inverse MDCT, window generation, and the cosine lookup that lets the
//! naïve transform run without runtime trig (spec §4.3.7 IMDCT, §4.3.8 window).
//!
//! # Naïve O(n²) IMDCT (the correctness oracle)
//!
//! [`imdct`] evaluates the inverse MDCT directly from its definition (spec
//! §1.3.2 / §4.3.7): for a block of `bs = 2·n` samples reconstructed from `n`
//! spectral lines,
//!
//! ```text
//! out[i] = Σ_{k=0}^{n-1} spec[k] · cos( (π/(2·bs)) · (2i+1+bs/2) · (2k+1) )
//! ```
//!
//! for `i = 0..bs`, with **no** `1/n`-style normalization applied here — this
//! matches libvorbis's `mdct_backward`, whose only scaling lives in the
//! encoder's forward transform (libvorbis normalizes the *forward* MDCT by
//! `2/n`, so the inverse is unnormalized). Paired with the Vorbis window applied
//! on synthesis and 50 % overlap-add (windows satisfy `w²+w'² = 1`), this
//! reconstructs the encoder's PCM at libvorbis's absolute amplitude — the scale
//! the golden vs ffmpeg pins. (A `2/n` factor here — the textbook IMDCT-IV
//! normalization for an *unnormalized* forward — is self-consistent but leaves
//! the output `n/2` too small against a real libvorbis/ffmpeg stream.) This is
//! deliberately the un-optimized reference; a fast split-radix transform is a
//! later task, gated by this same golden.
//!
//! # No runtime transcendentals
//!
//! The core crate is `#![no_std]`, no-alloc, and forbids `libm`, so nothing here
//! calls `sin`/`cos`. The IMDCT's cosine argument is `2π·J/(4·bs)` for an integer
//! `J = (2i+1+bs/2)(2k+1)`; [`cos_from_quarter`] reads it off the shared
//! [`COS_QUARTER`] table (one quarter-period at `4·MAX_BLOCKSIZE` resolution),
//! reflecting the four quadrants. The window rising halves are likewise baked
//! (`WIN_*`). Both are generated by `cargo xtask gen-vorbis-tables` and CI-guarded
//! by `xtask verify`; the tests below re-derive their closed-form properties so
//! they cannot silently rot.

use super::MAX_BLOCKSIZE;

// Precomputed trig tables (see the module doc + xtask/src/vorbis_tables.rs):
//   COS_QUARTER_N: usize, COS_QUARTER: [f32; COS_QUARTER_N + 1],
//   WIN_32 .. WIN_4096: the window rising halves.
// Regenerate with `cargo xtask gen-vorbis-tables`.
include!("vorbis_tables.rs");

/// `cos(2π·r / (4·MAX_BLOCKSIZE))` for a phase index `r ∈ [0, 4·MAX_BLOCKSIZE)`,
/// reflected out of the stored quarter-period [`COS_QUARTER`]. `q =
/// COS_QUARTER_N = MAX_BLOCKSIZE` is the quarter length; the four quadrants map
/// as `+Q[r]`, `−Q[2q−r]`, `−Q[r−2q]`, `+Q[4q−r]`.
#[inline]
fn cos_from_quarter(r: usize) -> f32 {
    let q = COS_QUARTER_N;
    if r <= q {
        COS_QUARTER[r]
    } else if r <= 2 * q {
        -COS_QUARTER[2 * q - r]
    } else if r <= 3 * q {
        -COS_QUARTER[r - 2 * q]
    } else {
        COS_QUARTER[4 * q - r]
    }
}

/// Complex number for the FFT scratch (no-alloc, on-stack).
#[derive(Clone, Copy)]
struct Cpx {
    re: f32,
    im: f32,
}
impl Cpx {
    const ZERO: Cpx = Cpx { re: 0.0, im: 0.0 };
}

/// In-place iterative radix-2 DIT complex FFT (`a.len()` a power of two,
/// `≤ VFFT_TW_N`). `inverse` selects the `exp(+iθ)` kernel; **no** `1/N`
/// normalization (the IMDCT folds the whole scale into its final factor).
/// Twiddles come from the shared size-`VFFT_TW_N` tables: a length-`len`
/// sub-DFT's column-`j` twiddle is `VFFT_*[j·(VFFT_TW_N/len)]`, an index always
/// `< VFFT_TW_N/2`, so the lookup can never go out of bounds.
#[allow(clippy::needless_range_loop)]
fn fft(a: &mut [Cpx], inverse: bool) {
    let n = a.len();
    if n < 2 {
        return;
    }
    // Bit-reversal permutation.
    let mut j = 0usize;
    for i in 1..n {
        let mut bit = n >> 1;
        while j & bit != 0 {
            j ^= bit;
            bit >>= 1;
        }
        j ^= bit;
        if i < j {
            a.swap(i, j);
        }
    }
    let mut len = 2;
    while len <= n {
        let half = len / 2;
        let stride = VFFT_TW_N / len;
        let mut start = 0;
        while start < n {
            for k in 0..half {
                let idx = k * stride;
                let c = VFFT_COS[idx];
                let s = if inverse {
                    VFFT_SIN[idx]
                } else {
                    -VFFT_SIN[idx]
                };
                let b = a[start + k + half];
                let wr = b.re * c - b.im * s;
                let wi = b.re * s + b.im * c;
                let u = a[start + k];
                a[start + k] = Cpx {
                    re: u.re + wr,
                    im: u.im + wi,
                };
                a[start + k + half] = Cpx {
                    re: u.re - wr,
                    im: u.im - wi,
                };
            }
            start += len;
        }
        len <<= 1;
    }
}

/// Fast inverse MDCT via an `N/4`-point complex FFT — the exact MDCT→FFT
/// reduction the AAC filterbank uses, so this is the same math as [`imdct_naive`]
/// at `O(N log N)` instead of `O(N²)`. `scratch.len() == N/4` sets the size:
/// `spec` supplies the `N/2` coefficients, `out` receives `N` time samples scaled
/// by `scale` (Vorbis is unnormalized, so `scale = 1.0`). `tw_*` are the length
/// `N/4` pre/post twiddles `trig(2π(k+⅛)/N)`. Bounds-guarded: a size mismatch
/// returns without touching `out`, and every index is provably in range.
#[allow(clippy::needless_range_loop, clippy::too_many_arguments)]
fn imdct_fft(
    spec: &[f32],
    scratch: &mut [Cpx],
    tw_cos: &[f32],
    tw_sin: &[f32],
    out: &mut [f32],
    scale: f32,
) {
    let l = scratch.len();
    let m = 2 * l; // N/2 input coeffs
    let n = 4 * l; // N output samples
    if spec.len() < m || out.len() < n || tw_cos.len() < l || tw_sin.len() < l {
        return;
    }
    // Pre-twiddle: Z[k] = (spec[N/2-1-2k] + i·spec[2k]) · t[k].
    for k in 0..l {
        let a = spec[2 * k];
        let b = spec[m - 1 - 2 * k];
        let c = tw_cos[k];
        let s = tw_sin[k];
        scratch[k] = Cpx {
            re: b * c - a * s,
            im: b * s + a * c,
        };
    }
    fft(scratch, true);
    // Post-twiddle.
    for k in 0..l {
        let re = scratch[k].re;
        let im = scratch[k].im;
        let c = tw_cos[k];
        let s = tw_sin[k];
        scratch[k] = Cpx {
            re: re * c - im * s,
            im: re * s + im * c,
        };
    }
    // Reorder into the N outputs (same layout as the AAC §10 IMDCT).
    let n8 = n / 8;
    let n4 = n / 4;
    let n2 = n / 2;
    for k in 0..n8 {
        out[2 * k] = scratch[n8 + k].im * scale;
        out[2 * k + 1] = -scratch[n8 - 1 - k].re * scale;
        out[n4 + 2 * k] = scratch[k].re * scale;
        out[n4 + 2 * k + 1] = -scratch[n4 - 1 - k].im * scale;
        out[n2 + 2 * k] = scratch[n8 + k].re * scale;
        out[n2 + 2 * k + 1] = -scratch[n8 - 1 - k].im * scale;
        out[n2 + n4 + 2 * k] = -scratch[k].im * scale;
        out[n2 + n4 + 2 * k + 1] = scratch[n4 - 1 - k].re * scale;
    }
}

/// Pre/post IMDCT rotation twiddles for block size `bs` (a power of two in
/// `[64, MAX_BLOCKSIZE]`); `None` for any other size (then [`imdct`] uses the
/// naïve fallback — unreachable for a spec-valid stream).
fn mdct_tw(bs: usize) -> Option<(&'static [f32], &'static [f32])> {
    Some(match bs {
        64 => (&VMDCT_COS_64, &VMDCT_SIN_64),
        128 => (&VMDCT_COS_128, &VMDCT_SIN_128),
        256 => (&VMDCT_COS_256, &VMDCT_SIN_256),
        512 => (&VMDCT_COS_512, &VMDCT_SIN_512),
        1024 => (&VMDCT_COS_1024, &VMDCT_SIN_1024),
        2048 => (&VMDCT_COS_2048, &VMDCT_SIN_2048),
        4096 => (&VMDCT_COS_4096, &VMDCT_SIN_4096),
        8192 => (&VMDCT_COS_8192, &VMDCT_SIN_8192),
        _ => return None,
    })
}

/// Inverse MDCT (spec §4.3.7): reconstruct `bs = 2·n` time samples in
/// `out[0..bs]` from the `n` spectral lines in `spec[0..n]`, **unnormalized** to
/// match libvorbis's `mdct_backward` scale. **O(N log N)** via an `N/4`-point FFT
/// ([`imdct_fft`]), with the naïve O(N²) reference ([`imdct_naive`]) as a fallback
/// for any block size lacking a precomputed twiddle table (none in a valid
/// stream). Never panics: sizes are bounds-checked and every index is in range.
pub(crate) fn imdct(spec: &[f32], n: usize, out: &mut [f32]) {
    let bs = 2 * n;
    if n == 0 || bs > MAX_BLOCKSIZE || out.len() < bs || spec.len() < n {
        return;
    }
    match mdct_tw(bs) {
        Some((tw_cos, tw_sin)) => {
            // Scratch = N/4 = n/2 complex points; libvorbis scale (unnormalized).
            let mut scratch = [Cpx::ZERO; MAX_BLOCKSIZE / 4];
            imdct_fft(
                &spec[..n],
                &mut scratch[..n / 2],
                tw_cos,
                tw_sin,
                &mut out[..bs],
                1.0,
            );
        }
        None => imdct_naive(spec, n, out),
    }
}

/// Naïve inverse MDCT (spec §4.3.7) — the direct-sum **reference/oracle** the
/// fast [`imdct`] is validated against, and the fallback for an unusual block
/// size. Unnormalized (no `1/n` factor) to match libvorbis's `mdct_backward`
/// scale (see the module docs). `bs` is always a power of two in
/// `[64, MAX_BLOCKSIZE]`, so `MAX_BLOCKSIZE/bs` is an exact integer stride onto
/// the shared cosine table. Slices shorter than required are left untouched past
/// their length (never panics): the loops are bounded by `n`/`bs` and every
/// table index is provably in range.
fn imdct_naive(spec: &[f32], n: usize, out: &mut [f32]) {
    let bs = 2 * n;
    if n == 0 || bs > MAX_BLOCKSIZE || out.len() < bs || spec.len() < n {
        return;
    }
    let stride = (COS_QUARTER_N / bs) as u64; // MAX_BLOCKSIZE / bs, exact
    let half = (bs / 2) as u64;
    // Full cosine period in table-index units: `((a·(2k+1)) mod 4·bs)·stride ==
    // (a·(2k+1)·stride) mod (4·bs·stride)`, and `4·bs·stride == 4·COS_QUARTER_N`.
    let period = 4 * COS_QUARTER_N as u64;
    // `i` drives both the cosine phase `a` and the output index, so the range
    // loop reads more directly than an enumerated iterator.
    #[allow(clippy::needless_range_loop)]
    for i in 0..bs {
        // a = (2i + 1 + bs/2); the running cosine argument is a·(2k+1). As `k`
        // steps, the table phase `r` advances by a constant `delta` — so the
        // innermost loop is an add + conditional subtract, not a 64-bit modulo
        // (an integer division was the dominant cost of this O(n²) transform).
        let a = (2 * i as u64) + 1 + half;
        let delta = (2 * a * stride) % period;
        let mut r = (a * stride) % period; // phase at k = 0 (b = 1)
        let mut acc = 0.0f32;
        for (_k, &xk) in spec.iter().enumerate().take(n) {
            acc += xk * cos_from_quarter(r as usize);
            r += delta;
            if r >= period {
                r -= period;
            }
        }
        out[i] = acc;
    }
}

/// The Vorbis window rising half of length `half_len = blocksize/2` (spec
/// §4.3.8). `half_len` is always `2^(e-1)` for a valid block-size exponent
/// `e ∈ 6..=13`; an unexpected length yields an empty slice (the caller then
/// leaves that window region at its initialized value — it never indexes past
/// the returned slice).
fn window_half(half_len: usize) -> &'static [f32] {
    match half_len {
        32 => &WIN_32,
        64 => &WIN_64,
        128 => &WIN_128,
        256 => &WIN_256,
        512 => &WIN_512,
        1024 => &WIN_1024,
        2048 => &WIN_2048,
        4096 => &WIN_4096,
        _ => &[],
    }
}

/// Build the length-`bs` Vorbis synthesis window into `w[0..bs]` (spec §4.3.8).
///
/// `blockflag` is this block's mode flag (long = `true`); `prev_window` /
/// `next_window` are the two per-long-block shape bits (a cleared flag means the
/// neighbouring block is short, so that side's slope is compressed to the short
/// window and flanked by flat/zero regions). `bs0` is `blocksize_0` (the short
/// block size). The falling (right) slope is the rising half read in reverse —
/// the window is symmetric.
///
/// Only `w[0..bs]` is written; the region outside `[left_start, right_end)` is
/// set to `0`/`1` explicitly, so no stale scratch leaks into the transform.
pub(crate) fn build_window(
    blockflag: bool,
    prev_window: bool,
    next_window: bool,
    bs: usize,
    bs0: usize,
    w: &mut [f32],
) {
    if bs > w.len() {
        return;
    }
    let center = bs / 2;
    let (left_start, left_end, left_n) = if blockflag && !prev_window {
        (bs / 4 - bs0 / 4, bs / 4 + bs0 / 4, bs0 / 2)
    } else {
        (0, center, bs / 2)
    };
    let (right_start, right_end, right_n) = if blockflag && !next_window {
        (bs * 3 / 4 - bs0 / 4, bs * 3 / 4 + bs0 / 4, bs0 / 2)
    } else {
        (center, bs, bs / 2)
    };

    for v in w.iter_mut().take(left_start) {
        *v = 0.0;
    }
    let rise = window_half(left_n);
    // `i` indexes the output window while `i - left_start` indexes the rising
    // half — a range loop keeps both offsets explicit.
    #[allow(clippy::needless_range_loop)]
    for i in left_start..left_end {
        w[i] = rise.get(i - left_start).copied().unwrap_or(0.0);
    }
    for v in w.iter_mut().take(right_start).skip(left_end) {
        *v = 1.0;
    }
    // Falling slope: the rising half reversed (window symmetry).
    let fall = window_half(right_n);
    // `i` indexes the output window while `right_end - 1 - i` reads the rising
    // half in reverse — a range loop keeps both offsets explicit.
    #[allow(clippy::needless_range_loop)]
    for i in right_start..right_end {
        w[i] = fall.get(right_end - 1 - i).copied().unwrap_or(0.0);
    }
    for v in w.iter_mut().take(bs).skip(right_end) {
        *v = 0.0;
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use core::f64::consts::PI;

    /// Direct Vorbis IMDCT sum in f64 (test-only; std trig is available under
    /// cfg(test)): out[i] = Σ spec[k]·cos((π/(2bs))(2i+1+bs/2)(2k+1)). Matches
    /// [`imdct`]'s libvorbis-scale (unnormalized — no `1/n` factor) convention.
    fn imdct_direct(spec: &[f64]) -> Vec<f64> {
        let n = spec.len();
        let bs = 2 * n;
        (0..bs)
            .map(|i| {
                let a = (2 * i + 1 + bs / 2) as f64;
                let mut acc = 0.0;
                for (k, &xk) in spec.iter().enumerate() {
                    let b = (2 * k + 1) as f64;
                    acc += xk * (PI / (2.0 * bs as f64) * a * b).cos();
                }
                acc
            })
            .collect()
    }

    #[test]
    fn cos_lookup_matches_std_cos_for_every_block_size() {
        // For each supported block size, the table-driven cosine must match the
        // exact formula cos(2π·J/(4bs)) across a spread of arguments.
        for &bs in &[64usize, 256, 2048, 8192] {
            let four_bs = (4 * bs) as u64;
            let stride = (COS_QUARTER_N / bs) as u64;
            let mut maxerr = 0.0f64;
            for j in 0..(4 * bs as u64) {
                let r = ((j % four_bs) * stride) as usize;
                let got = cos_from_quarter(r) as f64;
                let want = (2.0 * PI * j as f64 / four_bs as f64).cos();
                maxerr = maxerr.max((got - want).abs());
            }
            assert!(maxerr < 1e-4, "bs {bs}: cos lookup maxerr {maxerr}");
        }
    }

    #[test]
    fn imdct_matches_direct_sum_single_and_multi_bin() {
        // A short block (n = 128): a few bins must reproduce the direct sum.
        let mut spec = [0.0f64; 128];
        spec[3] = 0.7;
        spec[20] = -0.9;
        spec[64] = 0.31;
        let direct = imdct_direct(&spec);
        let specf: [f32; 128] = core::array::from_fn(|i| spec[i] as f32);
        let mut out = [0.0f32; 256];
        imdct(&specf, 128, &mut out);
        let mut maxerr = 0.0f64;
        for i in 0..256 {
            maxerr = maxerr.max((out[i] as f64 - direct[i]).abs());
        }
        assert!(maxerr < 1e-3, "imdct vs direct maxerr {maxerr}");
    }

    #[test]
    fn imdct_zero_spectrum_is_zero() {
        let mut out = [1.0f32; 4096];
        imdct(&[0.0f32; 2048], 2048, &mut out);
        assert!(out.iter().all(|&v| v.abs() < 1e-9));
    }

    /// The fast `N/4`-FFT [`imdct`] must agree with the direct-sum
    /// [`imdct_naive`] oracle for **every** supported block size, over a
    /// deterministic pseudo-random spectrum — the proof the FFT reduction
    /// (pre/post twiddles + reorder + scale) is the same transform.
    #[test]
    fn fast_imdct_matches_naive_for_every_block_size() {
        for e in 6..=13u32 {
            let bs = 1usize << e;
            if bs > MAX_BLOCKSIZE {
                break;
            }
            let n = bs / 2;
            // Deterministic LCG spectrum in ~[-1, 1].
            let mut x = 0x9e37_79b9u32;
            let spec: Vec<f32> = (0..n)
                .map(|_| {
                    x = x.wrapping_mul(1_664_525).wrapping_add(1_013_904_223);
                    (x >> 8) as f32 / (1u32 << 24) as f32 - 0.5
                })
                .collect();
            let mut fast = vec![0.0f32; bs];
            let mut naive = vec![0.0f32; bs];
            imdct(&spec, n, &mut fast);
            imdct_naive(&spec, n, &mut naive);
            let max_abs = naive.iter().fold(0.0f32, |m, &v| m.max(v.abs()));
            let max_err = fast
                .iter()
                .zip(&naive)
                .fold(0.0f32, |m, (&a, &b)| m.max((a - b).abs()));
            // f32 FFT vs f32 direct sum: only accumulation-order rounding differs.
            assert!(
                max_err <= 1e-3 * (max_abs + 1e-6),
                "bs {bs}: fast vs naive max_err {max_err} (max_abs {max_abs})"
            );
        }
    }

    /// The full symmetric long window (both flags set) satisfies the
    /// Princen–Bradley reconstruction identity `w[i]² + w[i+bs/2]² ≈ 1`, the
    /// property that makes 50 % overlap-add reconstruct the signal.
    #[test]
    fn long_window_satisfies_princen_bradley() {
        for &bs in &[256usize, 2048] {
            let mut w = [0.0f32; 2048];
            build_window(true, true, true, bs, 256, &mut w);
            let half = bs / 2;
            let mut maxerr = 0.0f64;
            for i in 0..half {
                let a = w[i] as f64;
                let b = w[i + half] as f64;
                maxerr = maxerr.max((a * a + b * b - 1.0).abs());
            }
            assert!(maxerr < 1e-4, "bs {bs}: PB maxerr {maxerr}");
            // Endpoints: rises from ~0, symmetric fall back to ~0.
            assert!((w[0] as f64) < 0.05);
            assert!(w[half - 1] > 0.99 && w[half] > 0.99);
            assert!((w[bs - 1] as f64) < 0.05);
        }
    }

    /// A long block flanked by short neighbours (both flags cleared) has its
    /// slopes compressed to the short window and flat/zero flanks — and the
    /// compressed slope regions still satisfy Princen–Bradley against a
    /// hypothetical adjacent short block.
    #[test]
    fn long_start_stop_window_has_compressed_slopes() {
        let bs = 2048usize;
        let bs0 = 256usize;
        let mut w = [0.0f32; 2048];
        build_window(true, false, false, bs, bs0, &mut w);
        // Left flank zero until bs/4 - bs0/4 = 512 - 64 = 448, then a short rise.
        assert!(w[..448].iter().all(|&v| v == 0.0));
        assert!(w[447] == 0.0 && w[448] > 0.0);
        // Flat 1.0 across the middle.
        assert!((w[1024] - 1.0).abs() < 1e-6);
        // Right flank zero after bs*3/4 + bs0/4 = 1536 + 64 = 1600.
        assert!(w[1600..bs].iter().all(|&v| v == 0.0));
        assert!(w[1599] > 0.0 && w[1600] == 0.0);
    }

    /// End-to-end reconstruction: a synthetic all-long signal windowed, forward-
    /// MDCT'd, inverse-MDCT'd, re-windowed and 50 % overlap-added must reproduce
    /// the middle of the original signal — the proof the IMDCT scale + window
    /// pair is self-consistent (the golden then pins it to libvorbis's *absolute*
    /// scale). The forward here carries the `2/n` normalization (as libvorbis's
    /// forward MDCT does) so it pairs with [`imdct`]'s unnormalized inverse; that
    /// forward/inverse split — not a `2/n` on the inverse — is what the golden
    /// vs ffmpeg vindicated.
    #[test]
    fn windowed_overlap_add_reconstructs_a_signal() {
        let bs = 256usize;
        let n = bs / 2;
        let mut w = [0.0f32; 256];
        build_window(true, true, true, bs, bs, &mut w);

        // A deterministic signal over three overlapping blocks.
        let sig = |t: usize| -> f64 {
            let t = t as f64;
            0.6 * (0.03 * t).sin() + 0.3 * (0.11 * t + 0.7).sin()
        };

        // Forward MDCT of block starting at `base` (windowed), carrying the
        // libvorbis `2/n` forward normalization: X[k] =
        // (2/n)·Σ_i w[i]·x[base+i]·cos((π/(2bs))(2i+1+bs/2)(2k+1)).
        let forward = |base: usize| -> Vec<f32> {
            (0..n)
                .map(|k| {
                    let mut acc = 0.0f64;
                    #[allow(clippy::needless_range_loop)]
                    for i in 0..bs {
                        let a = (2 * i + 1 + bs / 2) as f64;
                        let b = (2 * k + 1) as f64;
                        acc += w[i] as f64 * sig(base + i) * (PI / (2.0 * bs as f64) * a * b).cos();
                    }
                    (acc * 2.0 / n as f64) as f32
                })
                .collect()
        };

        // Three blocks at 50 % overlap: bases 0, n, 2n, placed at output offsets
        // 0, n, 2n (each spans bs, so the buffer must hold 2n + bs = 512).
        let mut recon = [0.0f32; 512];
        for (bi, base) in [0usize, n, 2 * n].iter().enumerate() {
            let x = forward(*base);
            let mut td = [0.0f32; 256];
            imdct(&x, n, &mut td);
            for i in 0..bs {
                // Place windowed block at output offset bi*n.
                let o = bi * n + i;
                if o < recon.len() {
                    recon[o] += td[i] * w[i];
                }
            }
        }
        // The fully-overlapped region is [2n, 3n) (covered by blocks 1 and 2).
        let mut maxerr = 0.0f64;
        #[allow(clippy::needless_range_loop)]
        for t in (2 * n)..(3 * n) {
            maxerr = maxerr.max((recon[t] as f64 - sig(t)).abs());
        }
        assert!(maxerr < 1e-3, "overlap-add reconstruction maxerr {maxerr}");
    }
}
