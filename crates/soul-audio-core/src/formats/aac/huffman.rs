/// Longest codeword in any spectral codebook (cb3, 16 bits) — bounds the
/// codeword-matching loop so it always terminates, even on a corrupt stream.
const MAX_SPECTRAL_LEN: u32 = 16;
/// Longest scalefactor-book codeword (19 bits).
const MAX_SF_LEN: u32 = 19;

/// Match a Huffman codeword MSB-first against a `(codes, bits)` table,
/// returning the table index. Reads one bit at a time and does a linear scan
/// at each length for an exact `(code, len)` match: correct because AAC's
/// codebooks are prefix-free (no partial codeword can equal a shorter
/// complete codeword), and bounded by `max_len` so a corrupt/mismatched
/// stream can never spin or read out of bounds (`BitReader` zero-pads past
/// the end of its input, so this always terminates in `Malformed` rather
/// than hanging).
fn match_huffman(
    r: &mut BitReader,
    codes: &[u16],
    bits: &[u8],
    max_len: u32,
) -> Result<usize, DecodeError> {
    let mut code: u32 = 0;
    for len in 1..=max_len {
        code = (code << 1) | r.read_bit();
        for (i, (&c, &b)) in codes.iter().zip(bits.iter()).enumerate() {
            if u32::from(b) == len && u32::from(c) == code {
                return Ok(i);
            }
        }
    }
    Err(DecodeError::Malformed)
}

/// Same as [`match_huffman`] but against the 32-bit-coded scalefactor book
/// (codewords up to 19 bits, too wide for a `u16` table).
fn match_huffman_u32(
    r: &mut BitReader,
    codes: &[u32],
    bits: &[u8],
    max_len: u32,
) -> Result<usize, DecodeError> {
    let mut code: u32 = 0;
    for len in 1..=max_len {
        code = (code << 1) | r.read_bit();
        for (i, (&c, &b)) in codes.iter().zip(bits.iter()).enumerate() {
            if u32::from(b) == len && c == code {
                return Ok(i);
            }
        }
    }
    Err(DecodeError::Malformed)
}

/// Convert an unpacked digit (`0..m`) to its coefficient value: for signed
/// codebooks (1,2,5,6) the digit already centers on zero (subtract the
/// alphabet's midpoint, `(m-1)/2` — 1 for m=3, 4 for m=9); unsigned
/// codebooks (3,4,7,8,9,10,11) use the digit directly and get their sign
/// from a separate bit ([`apply_sign_bits`]).
#[inline]
fn digit_value(digit: i32, m: i32, signed: bool) -> i32 {
    if signed { digit - (m - 1) / 2 } else { digit }
}

/// Read one sign bit per *nonzero* entry in `vals` (bitstream/coefficient
/// order), negating the value on a set bit. Unsigned codebooks only.
fn apply_sign_bits(r: &mut BitReader, vals: &mut [i32]) {
    for v in vals.iter_mut() {
        if *v != 0 && r.read_bit() == 1 {
            *v = -*v;
        }
    }
}

/// Codebook-11 escape (§6 / faad2 `huffman_getescape`): if `|*v| != 16` (the
/// pair's largest normal magnitude), `*v` is already final and this is a
/// no-op. Otherwise: count leading 1-bits `n` (bounded to `n < 12`, i.e.
/// `i_esc = n + 4` stays `< 16` — an unterminated run past that is malformed
/// input, not a valid escape), consume the terminating 0 bit, read `i_esc`
/// more bits as `off`, and set `*v = sign * ((1 << i_esc) + off)`.
fn apply_escape(r: &mut BitReader, v: &mut i32) -> Result<(), DecodeError> {
    if *v != 16 && *v != -16 {
        return Ok(());
    }
    let neg = *v < 0;
    let mut n: u32 = 0;
    while n < 12 {
        if r.read_bit() == 0 {
            break;
        }
        n += 1;
    }
    if n >= 12 {
        return Err(DecodeError::Malformed);
    }
    let i_esc = n + 4;
    let off = r.read(i_esc) as i32;
    let mag = (1i32 << i_esc) + off;
    *v = if neg { -mag } else { mag };
    Ok(())
}

/// Decode one Huffman tuple with spectral codebook `cb` (1..=11): a signed
/// quad (cb 1-4) or a signed pair (cb 5-11, returned in `[0]`/`[1]` with
/// `[2]`/`[3]` left `0`), applying sign bits (unsigned books) and the
/// codebook-11 escape, per `aac-reference.md` §6.
///
/// The innermost step of `syntax::spectral_data`.
pub(super) fn decode_spectral(r: &mut BitReader, cb: u8) -> Result<[i32; 4], DecodeError> {
    if !(1..=11).contains(&cb) {
        return Err(DecodeError::Malformed);
    }
    let props = &CB_PROPS[(cb - 1) as usize];
    let idx = match_huffman(r, props.codes, props.bits, MAX_SPECTRAL_LEN)? as i32;
    let m = props.m;
    let mut out = [0i32; 4];
    if props.dim == 4 {
        let m2 = m * m;
        let m3 = m2 * m;
        out[0] = digit_value(idx / m3, m, props.signed);
        out[1] = digit_value((idx / m2) % m, m, props.signed);
        out[2] = digit_value((idx / m) % m, m, props.signed);
        out[3] = digit_value(idx % m, m, props.signed);
    } else {
        out[0] = digit_value(idx / m, m, props.signed);
        out[1] = digit_value(idx % m, m, props.signed);
    }
    if !props.signed {
        apply_sign_bits(r, &mut out[..props.dim]);
        if cb == 11 {
            apply_escape(r, &mut out[0])?;
            apply_escape(r, &mut out[1])?;
        }
    }
    Ok(out)
}

/// Decode one scalefactor-book codeword, returning the raw index `0..120`
/// (the caller subtracts 60 for the DPCM differential, per `aac-reference.md`
/// §5's `scale_factor_data`/`huffman_sf`).
///
/// Consumed by `syntax::scale_factor_data`.
pub(super) fn decode_scalefactor(r: &mut BitReader) -> Result<i32, DecodeError> {
    let idx = match_huffman_u32(r, &SF_CODES, &SF_BITS, MAX_SF_LEN)?;
    Ok(idx as i32)
}

