//! (sign bits, then the codebook-11 escape) was cross-checked against faad2
//! `libfaad/huffman.c` (`huffman_spectral_data`, `huffman_getescape`):
//! decode the pair/quad, read one sign bit per *nonzero* coefficient
//! (unsigned books only), then — codebook 11 only — resolve any coefficient
//! whose magnitude is exactly the largest normal value (16) via the escape
//! sequence.

