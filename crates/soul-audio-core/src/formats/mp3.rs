    /// FNV-1a over the interleaved samples (each `i32` folded to its low 32 bits).
    fn fnv(samples: &[i32]) -> u64 {
        let mut h: u64 = 0xcbf2_9ce4_8422_2325;
        for &s in samples {
            h ^= u64::from(s as u32);
            h = h.wrapping_mul(0x0100_0000_01b3);
        }
        h
    }

    fn decode_all(mp3: &[u8], chunk: usize) -> Vec<i32> {
        let mut dec = Mp3Decoder::new(SliceSource::new(mp3)).unwrap();
        let mut all = Vec::new();
        let mut buf = vec![0i32; chunk];
        loop {
            let n = dec.decode_into(&mut buf).unwrap();
            if n == 0 {
                break;
            }
            all.extend_from_slice(&buf[..n]);
        }
        all
    }

    /// Seek a fresh decoder to per-channel `sample`, then drain the rest.
    /// Returns `(landed_first_sample, interleaved_pcm)`.
    fn decode_from_seek(mp3: &[u8], sample: u64) -> (u64, Vec<i32>) {
        let mut dec = Mp3Decoder::new(SliceSource::new(mp3)).unwrap();
        let landed = dec.seek_to(sample).unwrap();
        let mut all = Vec::new();
        let mut buf = [0i32; 512];
        loop {
            let n = dec.decode_into(&mut buf).unwrap();
            if n == 0 {
                break;
            }
            all.extend_from_slice(&buf[..n]);
        }
        (landed, all)
    }

    #[test]
    fn mp3_seek_to_zero_after_partial_is_bit_exact() {
        // At frame 0 the reservoir + filterbank start empty, so a seek(0) reset is
        // a *full* reset — the decode must be byte-identical to a fresh one.
        let full = decode_all(STEREO_MP3, 4096);
        let mut dec = Mp3Decoder::new(SliceSource::new(STEREO_MP3)).unwrap();
        let mut buf = [0i32; 3000];
        let _ = dec.decode_into(&mut buf).unwrap(); // partial decode leaves state
        assert_eq!(dec.seek_to(0).unwrap(), 0);
        let mut rest = Vec::new();
        loop {
            let n = dec.decode_into(&mut buf).unwrap();
            if n == 0 {
                break;
            }
            rest.extend_from_slice(&buf[..n]);
        }
        assert_eq!(rest, full);
    }

