//! MP3 decoder = [`Mp3Demuxer`](crate::demux::Mp3Demuxer) (container) + the
//! [`mp3_codec`](crate::formats::mp3_codec) Layer III codec.
//!
//! The demuxer packetizes one MPEG frame per call; this module drives the codec
//! frame by frame, streaming the decoded interleaved PCM to the caller and
//! carrying the codec's bit reservoir / filterbank state across frames.
//!
//! Output matches the WAV/FLAC convention: interleaved `i32` in 16-bit range
//! (`[-32768, 32767]`), no rescaling. Mono and stereo only.

use crate::decoder::{DecodeError, Decoder, secs_to_samples};
use crate::demux::{Demuxer, Mp3Demuxer};
use crate::formats::mp3_codec::Mp3Codec;
use crate::io::{SeekSource, Source};
use crate::model::StreamInfo;

/// MPEG Layer III decoder delay (per-channel samples): the subband-synthesis
/// filterbank's group delay, present as leading output samples before the first
/// true sample. Added to the LAME/Lavc encoder delay for the gapless leading
/// skip, matching LAME's `DECODERDELAY` and ffmpeg's `528 + 1`.
const MP3_DECODER_DELAY: u64 = 529;

/// Largest MPEG frame we packetize/decode. The worst case is MPEG-1 Layer II at
/// 384 kbps / 32 kHz = 1728 bytes (Layer III tops out at 1441); round up for
/// headroom. Larger (free-format) frames are declined by the demuxer.
const MAX_FRAME: usize = 2048;
/// Interleaved PCM samples one frame can yield: 1152 per channel × 2 channels.
const MAX_PCM: usize = 1152 * 2;

/// MP3 decoder over a byte [`Source`]. Decodes MPEG-1/2/2.5 Layer III frames to
/// interleaved `i32` PCM.
pub struct Mp3Decoder<S> {
    demux: Mp3Demuxer<S>,
    codec: Mp3Codec,
    /// Scratch holding one demuxed MPEG frame (header + body).
    frame_buf: [u8; MAX_FRAME],
    /// Decoded interleaved PCM for the current frame.
    pcm: [i32; MAX_PCM],
    /// Number of valid interleaved samples in [`Self::pcm`].
    pcm_len: usize,
    /// Emit cursor within [`Self::pcm`].
    pcm_pos: usize,
}

impl<S: Source> Mp3Decoder<S> {
    /// Skip ID3, parse the first frame header, and prepare to stream PCM.
    ///
    /// # Errors
    /// Propagates [`Mp3Demuxer::new`] errors; [`DecodeError::Unsupported`] for a
    /// stream with more than two channels (Layer III tops out at stereo, so this
    /// should not occur in valid streams).
    pub fn new(src: S) -> Result<Self, DecodeError> {
        let demux = Mp3Demuxer::new(src)?;
        let channels = demux.stream_info().channels;
        if channels == 0 || channels > 2 {
            return Err(DecodeError::Unsupported);
        }
        Ok(Self {
            demux,
            codec: Mp3Codec::new(),
            frame_buf: [0; MAX_FRAME],
            pcm: [0; MAX_PCM],
            pcm_len: 0,
            pcm_pos: 0,
        })
    }

    /// Pull and decode frames until one yields PCM, filling [`Self::pcm`].
    /// Returns `false` at end of stream. Frames that decode to zero samples
    /// (e.g. before the bit reservoir is primed) are skipped transparently.
    fn refill(&mut self) -> Result<bool, DecodeError> {
        self.pcm_pos = 0;
        self.pcm_len = 0;
        loop {
            let n = match self.demux.next_packet(&mut self.frame_buf)? {
                None => return Ok(false),
                // A malformed frame in an otherwise valid stream decodes to 0
                // samples and is skipped by the loop.
                Some(packet) => self
                    .codec
                    .decode_frame(packet.data, &mut self.pcm)
                    .unwrap_or(0),
            };
            if n > 0 {
                self.pcm_len = n;
                return Ok(true);
            }
        }
    }
}

impl<S: Source> Mp3Decoder<S> {
    /// Encoded duration in per-channel samples, from the Xing/Info/VBRI header if
    /// present (excludes the leading tag frame). `None` for a raw stream without
    /// such a header.
    #[must_use]
    pub fn total_samples(&self) -> Option<u64> {
        self.demux.total_samples()
    }

    /// Total per-channel frames, if the stream declares a length (Xing/Info/VBRI).
    /// Alias of [`total_samples`](Self::total_samples) for a uniform decoder API.
    #[must_use]
    pub fn total_frames(&self) -> Option<u64> {
        self.demux.total_samples()
    }
}

impl<S: SeekSource> Mp3Decoder<S> {
    /// Seek to (the frame containing) per-channel `sample`. Returns the first
    /// sample of the landed frame (≤ `sample`).
    ///
    /// MP3 seeking is **frame-granular, not sample-accurate**: a granule's main
    /// data can live in the bit reservoir of *earlier* frames, and the IMDCT/QMF
    /// filterbank carries overlap between frames. After a seek both are reset, so
    /// the first decoded samples are a warm-up transient that differs from a
    /// continuous decode — this is inherent to the format (minimp3/dr_mp3 behave
    /// the same). Steady state is reached within one frame.
    ///
    /// # Errors
    /// Propagates the demuxer seek error.
    pub fn seek_to(&mut self, sample: u64) -> Result<u64, DecodeError> {
        let spf = u64::from(self.demux.samples_per_frame());
        let landed = self.demux.seek_to_frame(sample / spf)?;
        self.codec.reset();
        self.pcm_len = 0;
        self.pcm_pos = 0;
        Ok(landed)
    }

    /// Seek to `secs` seconds (convenience over [`Self::seek_to`]). Returns the
    /// first sample of the landed frame.
    ///
    /// # Errors
    /// Propagates [`Self::seek_to`] errors.
    pub fn seek_to_time(&mut self, secs: f64) -> Result<u64, DecodeError> {
        self.seek_to(secs_to_samples(secs, self.demux.stream_info().sample_rate))
    }
}

impl<S: Source> Decoder for Mp3Decoder<S> {
    fn stream_info(&self) -> StreamInfo {
        self.demux.stream_info()
    }

    fn decode_into(&mut self, out: &mut [i32]) -> Result<usize, DecodeError> {
        let mut w = 0;
        while w < out.len() {
            if self.pcm_pos >= self.pcm_len && !self.refill()? {
                break;
            }
            out[w] = self.pcm[self.pcm_pos];
            self.pcm_pos += 1;
            w += 1;
        }
        Ok(w)
    }

    fn encoder_delay(&self) -> u64 {
        // Gapless leading samples this decoder emits before the first true
        // sample, summed:
        //   * one `spf` frame — the Xing/Info **tag frame** itself, which the
        //     demuxer serves as the first packet and we decode to silence
        //     (matching minimp3); ffmpeg instead drops it as a header, so it is
        //     part of OUR leading offset,
        //   * the LAME/Lavc info-tag **encoder delay** (priming/look-ahead),
        //   * the MPEG Layer III **decoder delay** (529 — the subband-synthesis
        //     filterbank group delay this decoder, like the reference, carries).
        // Only when a recognized info tag declared an encoder delay; a tagless
        // stream reports 0 (no reliable gapless info → no trim). Verified
        // against ffmpeg: `vbr-44100-stereo.mp3` = 1152 + 576 + 529 = 2257,
        // exactly where our decode aligns with ffmpeg's gapless output.
        let enc = self.demux.encoder_delay();
        if enc == 0 {
            0
        } else {
            u64::from(self.demux.samples_per_frame()) + u64::from(enc) + MP3_DECODER_DELAY
        }
    }
}

