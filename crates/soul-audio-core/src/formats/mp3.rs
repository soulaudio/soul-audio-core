    fn decode_all(mp3: &[u8], chunk: usize) -> Vec<i32> {
        let mut dec = Mp3Decoder::new(SliceSource::new(mp3)).unwrap();
        let mut all = Vec::new();
        let mut buf = vec![0i32; chunk];
        loop {
            let n = dec.decode_into(&mut buf).unwrap();
            if n == 0 {
                break;
            }
            all.extend_from_slice(&buf[..n]);
        }
        all
    }

    #[test]
    fn reports_stream_info() {
        let mono = Mp3Decoder::new(SliceSource::new(MONO_MP3)).unwrap();
        assert_eq!(mono.stream_info().sample_rate, 44_100);
        assert_eq!(mono.stream_info().channels, 1);
        assert_eq!(
            mono.stream_info().format,
            crate::model::SampleFormat::Int { bits: 16 }
        );

        let stereo = Mp3Decoder::new(SliceSource::new(STEREO_MP3)).unwrap();
        assert_eq!(stereo.stream_info().channels, 2);
    }

